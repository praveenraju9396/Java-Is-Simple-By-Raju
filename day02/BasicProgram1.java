package com.basics.day02;

public class BasicProgram1 {
    static void main() {
        System.out.println("hi");
        System.out.println("hello");
        System.out.println("namasthey");
    }
}


//EXPLANATION;
// EVERY METHOD IN JAVA SHOULD RETURN SOMETHING BUT WHEREAS MAIN METHOD [public static void main (String [] args)] SHOULD NOT RETURN ANYTHING THATS WHY WE KEEP IT AS VOID
// WITHOUT VOID FOR A MAIN METHOD WE CANNOT RUN BUT WITHOUT [PUBLIC STATIC STRING [] ARGS] WE CAN RUN
// EVERY PRINT STATEMENT ENDS WITH SEMICOLON
// WE CAN WRITE N NO OF PRINT STATEMENTS
// WHENEVER OUR CLASS NAME IS PUBLIC THEN BOTH  CLASS NAME AND FILE NAME MUST AND SHOULD BE SAME OTHERWISE CLASS NAME AND FILE NAME NO NEED TO BE SAME
//IF WE USE PUBLIC FOR A CLASS ,THEN THE CLASS CAN BE VISIBLE FROM ANYPLACE WITHIN THE PROJECT
